"""```markdown
# 9. VOC Electronic Nose Sensor Processing Module
This class processes raw analog MQ sensor signals, establishing and updating baseline trends.
```
"""

class VOCSensorProcessor:
    def __init__(self, baseline_window=10):
        self.readings = []
        self.baseline_window = baseline_window
        self.baseline = None

    def process_new_reading(self, raw_value):
        self.readings.append(raw_value)
        if len(self.readings) > 100:
            self.readings.pop(0)

        # Simple baseline calculation (moving minimum over local window)
        if len(self.readings) >= self.baseline_window:
            self.baseline = np.mean(sorted(self.readings)[:self.baseline_window])
        else:
            self.baseline = np.mean(self.readings)

        change_from_baseline = raw_value - self.baseline
        average = np.mean(self.readings)

        # Determine Trend direction
        if len(self.readings) < 3:
            trend = 'Stable'
        else:
            recent_avg = np.mean(self.readings[-3:])
            prior_avg = np.mean(self.readings[-6:-3]) if len(self.readings) >= 6 else self.readings[0]
            if recent_avg > prior_avg * 1.05:
                trend = 'Increasing'
            elif recent_avg < prior_avg * 0.95:
                trend = 'Decreasing'
            else:
                trend = 'Stable'

        return {
            'current_reading': raw_value,
            'baseline': round(self.baseline, 2),
            'change': round(change_from_baseline, 2),
            'average': round(average, 2),
            'trend': trend
        }

