"""```markdown
# 8. Multi-Frame YOLO Confirmation Logic & Inventory Updates
To prevent transient camera frame drops or false detections from modifying the inventory database immediately, we implement a multi-frame buffer. Only consistent counts across `N` consecutive frames trigger database commits.
```
"""

class InventoryTracker:
    def __init__(self, db_path, window_size=5):
        self.db_path = db_path
        self.window_size = window_size
        self.history = {'Banana': [], 'Orange': [], 'Tomato': []}

    def add_frame_detections(self, detections):
        for food, count in detections.items():
            if food in self.history:
                self.history[food].append(count)
                if len(self.history[food]) > self.window_size:
                    self.history[food].pop(0)

    def confirm_stable_quantity(self, food):
        history = self.history.get(food, [])
        if len(history) < self.window_size:
            return None
        if len(set(history)) == 1:
            return history[0]
        return None

    def update_database(self, food, confirmed_qty):
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()

        cursor.execute("SELECT current_quantity, opening_quantity, quantity_added, quantity_removed FROM inventory WHERE food_name = ?", (food,))
        row = cursor.fetchone()
        if not row:
            conn.close;
            return

        curr_qty, opening_qty, added_qty, removed_qty = row
        now = datetime.now()

        if now.day == 1 and curr_qty != opening_qty:
            opening_qty = curr_qty
            added_qty = 0
            removed_qty = 0

        if confirmed_qty != curr_qty:
            diff = confirmed_qty - curr_qty
            if diff > 0:
                added_qty += diff
            else:
                removed_qty += abs(diff)

            cursor.execute('''
                UPDATE inventory
                SET current_quantity = ?,
                    opening_quantity = ?,
                    quantity_added = ?,
                    quantity_removed = ?,
                    last_update = ?
                WHERE food_name = ?
            ''', (confirmed_qty, opening_qty, added_qty, removed_qty, now, food))

        conn.commit()
        conn.close()

